import assert from "node:assert/strict";
import { describe, it } from "node:test";
import {
  formatEnvValuePromptMessage,
  sharedEnvUpdates,
  summarizeEnvDoctor,
} from "./env.js";

void describe("bootstrap environment setup summary", () => {
  void it("treats env files as bootstrap-managed and only follows up on human values", () => {
    const summary = summarizeEnvDoctor(new Map());

    assert.equal(summary.success, false);
    assert.deepEqual(summary.followUpItems, [
      "Provide ANTHROPIC_API_KEY when bootstrap prompts for it.",
    ]);
    assert.match(summary.message, /ANTHROPIC_API_KEY — needed/);
    assert.match(
      summary.message,
      /ATLAS_AUTH_INTERNAL_SECRET — generated by setup/,
    );
    assert.match(
      summary.message,
      /ATLAS_AUTH_CALLBACK_SECRET — generated by setup/,
    );
    assert.match(
      summary.message,
      /ATLAS_EDGE_ORIGIN_SECRET — generated by setup/,
    );
    assert.doesNotMatch(summary.message, /\.env/);
    assert.equal(
      summary.followUpItems.some((item) => item.includes("Copy ")),
      false,
    );
  });

  void it("puts setup steps directly in human-provided value prompts", () => {
    const anthropic = formatEnvValuePromptMessage("ANTHROPIC_API_KEY");
    assert.match(
      anthropic,
      /Open https:\/\/console\.anthropic\.com\/settings\/keys/,
    );
    assert.match(anthropic, /Paste the value for ANTHROPIC_API_KEY here/);
    assert.match(anthropic, /Bootstrap writes this to \.env and API env files/);

    const resend = formatEnvValuePromptMessage("ATLAS_EMAIL_RESEND_API_KEY");
    assert.match(resend, /Open https:\/\/resend\.com\/api-keys/);
    assert.match(resend, /Verify the sender domain/);
    assert.match(resend, /leave blank to skip for now/);
  });
});

void describe("bootstrap shared env propagation", () => {
  void it("propagates every value set during this run", () => {
    const updates = new Map([
      ["ATLAS_AUTH_CALLBACK_SECRET", "generated-callback"],
      ["ANTHROPIC_API_KEY", "prompted-anthropic"],
    ]);

    const envUpdates = sharedEnvUpdates(
      new Map([["ATLAS_AUTH_CALLBACK_SECRET", "older-callback"]]),
      new Map(updates),
      updates,
    );

    assert.equal(
      envUpdates.get("ATLAS_AUTH_CALLBACK_SECRET"),
      "generated-callback",
    );
    assert.equal(envUpdates.get("ANTHROPIC_API_KEY"), "prompted-anthropic");
  });

  void it("fills generated secrets an older app env file never received", () => {
    const rootEnv = new Map([
      ["ATLAS_AUTH_INTERNAL_SECRET", "root-internal"],
      ["ATLAS_AUTH_CALLBACK_SECRET", "root-callback"],
      ["ATLAS_EDGE_ORIGIN_SECRET", "root-edge"],
    ]);
    const appEnv = new Map([
      ["ATLAS_AUTH_INTERNAL_SECRET", "root-internal"],
      ["ATLAS_AUTH_CALLBACK_SECRET", "replace-with-a-local-callback-secret"],
    ]);

    const envUpdates = sharedEnvUpdates(appEnv, rootEnv, new Map());

    assert.deepEqual(
      [...envUpdates.entries()].sort(([a], [b]) => a.localeCompare(b)),
      [
        ["ATLAS_AUTH_CALLBACK_SECRET", "root-callback"],
        ["ATLAS_EDGE_ORIGIN_SECRET", "root-edge"],
      ],
    );
  });

  void it("never overwrites a real value or copies a placeholder or a human-provided key", () => {
    const rootEnv = new Map([
      ["ATLAS_AUTH_CALLBACK_SECRET", "root-callback"],
      ["ATLAS_EDGE_ORIGIN_SECRET", "replace-with-a-local-edge-secret"],
      ["ANTHROPIC_API_KEY", "root-anthropic"],
    ]);
    const productionEnv = new Map([
      ["ATLAS_AUTH_CALLBACK_SECRET", "distinct-production-callback"],
      ["ANTHROPIC_API_KEY", "replace-with-your-anthropic-api-key"],
    ]);

    const envUpdates = sharedEnvUpdates(productionEnv, rootEnv, new Map());

    assert.equal(envUpdates.size, 0);
  });
});
