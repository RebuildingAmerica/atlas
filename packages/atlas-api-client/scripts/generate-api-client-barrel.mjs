import { readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(scriptDir, "..");
const generatedRoot = join(packageRoot, "src", "generated");
const clientRoot = join(generatedRoot, "atlas");
const schemasIndex = join(generatedRoot, "atlas-schemas", "index.ts");
const barrelPath = join(clientRoot, "index.ts");

function modulePath(fromDir, filePath) {
  const withoutExtension = filePath.replace(/\.ts$/, "");
  const relPath = relative(fromDir, withoutExtension).split(sep).join("/");
  return relPath.startsWith(".") ? relPath : `./${relPath}`;
}

function collectClientFiles() {
  const entries = readdirSync(clientRoot, { withFileTypes: true });
  const files = entries
    .filter((entry) => entry.isDirectory())
    .flatMap((entry) => {
      const tagDir = join(clientRoot, entry.name);
      return readdirSync(tagDir)
        .filter((file) => file.endsWith(".ts"))
        .map((file) => join(tagDir, file));
    })
    .filter((file) => statSync(file).isFile())
    .sort();

  if (files.length === 0) {
    throw new Error(`No generated API client files found in ${clientRoot}`);
  }

  return files;
}

statSync(schemasIndex);

const exports = [
  ...collectClientFiles().map(
    (file) => `export * from '${modulePath(clientRoot, file)}';`,
  ),
  `export * from '${modulePath(clientRoot, schemasIndex)}';`,
];

writeFileSync(
  barrelPath,
  [
    "/**",
    " * Generated by packages@rebuildingamerica/atlas-api-client/scripts/generate-api-client-barrel.mjs.",
    " * Do not edit manually.",
    " */",
    ...exports,
    "",
  ].join("\n"),
);
